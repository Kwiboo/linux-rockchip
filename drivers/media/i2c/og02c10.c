#define OG02C10_REG_MIRROR			0x3821
/* Align with ox03c10 RMW style; OG02C10 DS: flip 0x3820[2], mirror 0x3821[2] */
#define OG02C10_FLIP_BIT_MASK			BIT(2)
#define OG02C10_MIRROR_BIT_MASK			BIT(2)
