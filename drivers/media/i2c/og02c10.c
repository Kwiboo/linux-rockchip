static int __og02c10_start_stream(struct og02c10 *og02c10)
{
	int ret;

	ret = og02c10_write_array(og02c10->client, og02c10->cur_mode->reg_list);
	if (ret)
		return ret;

	/* In case these controls are set before streaming */
	ret = __v4l2_ctrl_handler_setup(&og02c10->ctrl_handler);
	if (ret)
		return ret;

	ret = og02c10_apply_sync_mode(og02c10);
	if (ret)
		return ret;

	usleep_range(1000, 5000);

	ret = og02c10_write_reg(og02c10->client, OG02C10_REG_CTRL_MODE,
				OG02C10_MODE_STREAMING);

	/*
	 * Linear10: FAE setting ends with 3208=e0/e1; after stream-on +
	 * ctrl setup, re-launch HCG (0xe0) so optical again/dgain follow
	 * 0x3508~0x350C. L/S gain are still mirrored in set_ctrl.
	 */
	if (!ret &&
	    og02c10->cur_mode->bus_fmt == MEDIA_BUS_FMT_SBGGR10_1X10)
		ret = og02c10_write_reg(og02c10->client,
					OG02C10_REG_GROUP_HOLD,
					OG02C10_GROUP_LAUNCH_HCG);

	return ret;
}

static int __og02c10_stop_stream(struct og02c10 *og02c10)
{
	return og02c10_write_reg(og02c10->client, OG02C10_REG_CTRL_MODE, OG02C10_MODE_SW_STANDBY);
}

static int og02c10_s_stream(struct v4l2_subdev *sd, int on)
{
	struct og02c10 *og02c10 = to_og02c10(sd);
	struct i2c_client *client = og02c10->client;
	int ret = 0;

	mutex_lock(&og02c10->mutex);
	on = !!on;
	if (on == og02c10->streaming)
		goto unlock_and_return;

	if (on) {
		ret = pm_runtime_get_sync(&client->dev);
		if (ret < 0) {
			v4l2_err(sd, "pm runtime get sync failed\n");
			pm_runtime_put_noidle(&client->dev);
			goto unlock_and_return;
		}

		ret = __og02c10_start_stream(og02c10);
		if (ret) {
			v4l2_err(sd, "start stream failed while write regs\n");
			pm_runtime_put(&client->dev);
			goto unlock_and_return;
		}
	} else {
		__og02c10_stop_stream(og02c10);
		pm_runtime_put(&client->dev);
	}

	og02c10->streaming = on;

unlock_and_return:
	mutex_unlock(&og02c10->mutex);

	return ret;
}

static int og02c10_s_power(struct v4l2_subdev *sd, int on)
{
	struct og02c10 *og02c10 = to_og02c10(sd);
	struct i2c_client *client = og02c10->client;
	int ret = 0;

	mutex_lock(&og02c10->mutex);

	/* If the power state is not modified - no work to do. */
	if (og02c10->power_on == !!on)
		goto unlock_and_return;

	if (on) {
		ret = pm_runtime_get_sync(&client->dev);
		if (ret < 0) {
			pm_runtime_put_noidle(&client->dev);
			goto unlock_and_return;
		}

		usleep_range(100, 200);

		og02c10->power_on = true;
	} else {
		pm_runtime_put(&client->dev);
		og02c10->power_on = false;
	}

unlock_and_return:
	mutex_unlock(&og02c10->mutex);

	return ret;
}

static int __og02c10_power_on(struct og02c10 *og02c10)
{
	int ret = 0;
	struct device *dev = &og02c10->client->dev;

	ret = clk_set_rate(og02c10->xvclk, OG02C10_XVCLK_FREQ);
	if (ret < 0)
		dev_warn(dev, "Failed to set xvclk rate (24MHz)\n");
	if (clk_get_rate(og02c10->xvclk) != OG02C10_XVCLK_FREQ)
		dev_warn(dev, "xvclk mismatched, modes are based on 24MHz\n");
	ret = clk_prepare_enable(og02c10->xvclk);
	if (ret < 0) {
		dev_err(dev, "Failed to enable xvclk\n");
		return ret;
	}

	ret = regulator_bulk_enable(OG02C10_NUM_SUPPLIES, og02c10->supplies);
	if (ret < 0)
		dev_err(dev, "Failed to enable regulators\n");

	if (!IS_ERR(og02c10->pwdn_gpio)) {
		ret = gpiod_direction_output(og02c10->pwdn_gpio, 1);
		if (ret < 0)
			dev_err(dev, "Failed to set pwdn gpio\n");
		usleep_range(3000, 5000);
	}

	if (!IS_ERR(og02c10->reset_gpio)) {
		ret = gpiod_direction_output(og02c10->reset_gpio, 1);
		if (ret < 0)
			dev_err(dev, "Failed to set reset gpio\n");
		usleep_range(3000, 5000);
	}

	return ret;
}

static void __og02c10_power_off(struct og02c10 *og02c10)
{
	struct device *dev = &og02c10->client->dev;
	int ret = 0;

	if (!IS_ERR(og02c10->reset_gpio)) {
		ret = gpiod_direction_output(og02c10->reset_gpio, 0);
		if (ret < 0)
			dev_err(dev, "Failed to set reset gpio\n");
		usleep_range(500, 1000);
	}
	if (!IS_ERR(og02c10->pwdn_gpio)) {
		ret = gpiod_direction_output(og02c10->pwdn_gpio, 0);
		if (ret < 0)
			dev_err(dev, "Failed to set pwdn gpio\n");
		usleep_range(500, 1000);
	}
	clk_disable_unprepare(og02c10->xvclk);
	regulator_bulk_disable(OG02C10_NUM_SUPPLIES, og02c10->supplies);
}

