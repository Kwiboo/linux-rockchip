#define OG02C10_LANES				2
/* V4L2_CID_LINK_FREQ is CSI-2 DDR clock (Hz).
 * Data rate = 2 * link_freq Mbps/lane (both-edge sampling).
 * Linear/DCG12: 1500Mbps/lane → 750MHz.
 */
#define MIPI_FREQ_750M				750000000UL
#define PIXEL_RATE_WITH_750M			(MIPI_FREQ_750M * 2 / 10 * OG02C10_LANES)
#define PIXEL_RATE_WITH_750M_12BIT		(MIPI_FREQ_750M * 2 / 12 * OG02C10_LANES)
#define OG02C10_XVCLK_FREQ			24000000
#define OG02C10_SCLK				96000000ULL

#define OG02C10_VTS_MAX				0xffff

#define OG02C10_REG_SC_SCCB_ID0			0x0107
#define OG02C10_REG_SC_SCCB_ID1			0x0109
#define OG02C10_REG_SC_SCCB_ID2			0x302B

#define OG02C10_GAIN_MIN			16
/* total = again * dgain; again<=15.5, dgain<=15 => 232.5x; val=total*16 */
#define OG02C10_GAIN_MAX			3720
#define OG02C10_GAIN_STEP			1
#define OG02C10_GAIN_DEFAULT			0x80
#define OG02C10_AGAIN_MAX_REG			248	/* 15.5x * 16 */
#define OG02C10_AGAIN_MIN_REG			16	/* 1.0x * 16 */
#define OG02C10_DGAIN_MAX			15
/*
 * DCG Combine (RAW12):
 * - HCG again min 8x, LCG again min 1.3125x, ratio fixed 8:1.3125 (128:21)
 * - Upper/AIQ gain is "logical": 1x..~29.06x (code 16..465)
 * - Driver maps: HCG_total = logical * 8  =>  logical 1x <=> HCG 8x
 * - LCG again = HCG_again * 21 / 128; HCG/LCG dgain unified
 */
#define OG02C10_DCG_HCG_AGAIN_REF		128	/* 8.0x */
#define OG02C10_DCG_LCG_AGAIN_REF		21	/* 1.3125x */
#define OG02C10_DCG_GAIN_SCALE			8	/* logical 1x -> HCG 8x */
#define OG02C10_DCG_GAIN_MIN			OG02C10_GAIN_MIN	/* logical 1x */
#define OG02C10_DCG_GAIN_MAX			(OG02C10_GAIN_MAX / OG02C10_DCG_GAIN_SCALE) /* 465 */
#define OG02C10_DCG_GAIN_DEFAULT		OG02C10_GAIN_MIN	/* logical 1x => HCG 8x */

/* Coarse exposure lines via 0x3500~02; FAE min line target=2.
 * Sub-line / ~2us in Linear needs fine exp 0x3506/3507 (sysclk), not wired yet.
 */
#define OG02C10_EXPOSURE_MIN			2
#define OG02C10_EXPOSURE_STEP			1

/*
 * 0x3208 is a command reg (same addr, different ops):
 * - 0x0N / 0x1N: start/end record group N (init tables)
 * - 0x00 / 0x10: runtime group0 hold for AE (exp/gain/vts)
 * - 0xA0: quick/delay launch of held group0 (DCG / generic)
 * - 0xE0 / 0xE1: launch HCG / LCG context (Linear needs E0 so 3508 path works)
 * Hold start/end do NOT select HCG/LCG; final launch value does.
 */
#define OG02C10_REG_GROUP_HOLD			0x3208
#define OG02C10_GROUP_LAUNCH_HCG		0xE0

#define OG02C10_REG_EXP_H			0x3500
#define OG02C10_REG_EXP_M			0x3501
#define OG02C10_REG_EXP_L			0x3502

#define OG02C10_REG_HTS_H			0x380C
#define OG02C10_REG_HTS_L			0x380D
#define OG02C10_REG_VTS_H			0x380E
#define OG02C10_REG_VTS_L			0x380F

#define OG02C10_REG_AGAIN_COARSE		0x3508
#define OG02C10_REG_AGAIN_FINE			0x3509

#define OG02C10_REG_DGAIN_COARSE		0x350A
#define OG02C10_REG_DGAIN_FINE_H		0x350B
#define OG02C10_REG_DGAIN_FINE_L		0x350C

/* S/LCG gain (AEC_CFG_S_*): Linear10 same as L; DCG = LCG @ 8:1.3125 vs HCG */
#define OG02C10_REG_AGAIN_S_COARSE		0x3548
#define OG02C10_REG_AGAIN_S_FINE		0x3549
#define OG02C10_REG_DGAIN_S_COARSE		0x354A
#define OG02C10_REG_DGAIN_S_FINE_H		0x354B
#define OG02C10_REG_DGAIN_S_FINE_L		0x354C

#define OG02C10_REG_CTRL_MODE			0x0100
#define OG02C10_MODE_SW_STANDBY			0x0
#define OG02C10_MODE_STREAMING			BIT(0)

#define OG02C10_REG_SOFTWARE_RESET		0x0103
#define OG02C10_SOFTWARE_RESET_VAL		0x1

#define OG02C10_REG_TEST_PATTERN		0x5E00
