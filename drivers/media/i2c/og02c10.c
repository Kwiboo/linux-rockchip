/* sensor register write */
static int og02c10_write_reg(struct i2c_client *client, u16 reg, u8 val)
{
	struct i2c_msg msg;
	u8 buf[3];
	int ret;

	buf[0] = (reg >> 8) & 0xFF;
	buf[1] = reg & 0xFF;
	buf[2] = val;

	msg.addr = client->addr;
	msg.flags = client->flags;
	msg.buf = buf;
	msg.len = sizeof(buf);

	ret = i2c_transfer(client->adapter, &msg, 1);
	if (ret >= 0)
		return 0;

	dev_err(&client->dev,
		"og02c10 write reg(0x%x val:0x%x) failed, ret=%d\n", reg, val, ret);

	return ret;
}

static int og02c10_write_array(struct i2c_client *client,
			       const struct regval *regs)
{
	int i, ret = 0;

	i = 0;
	while (regs[i].addr != REG_NULL) {
		ret = og02c10_write_reg(client, regs[i].addr, regs[i].val);
		if (ret) {
			dev_err(&client->dev, "%s failed, ret=%d\n", __func__, ret);
			break;
		}
		i++;
	}

	return ret;
}

static int og02c10_apply_sync_mode(struct og02c10 *og02c10)
{
	const struct regval *regs;

	switch (og02c10->sync_mode) {
	case INTERNAL_MASTER_MODE:
	case NO_SYNC_MODE:
		return 0;
	case SLAVE_MODE:
		regs = og02c10_slave_regs;
		break;
	default:
		dev_err(&og02c10->client->dev, "unsupported sync mode %u\n",
			og02c10->sync_mode);
		return -EINVAL;
	}

	return og02c10_write_array(og02c10->client, regs);
}

/* sensor register read */
static int og02c10_read_reg(struct i2c_client *client, u16 reg, u8 *val)
{
	struct i2c_msg msg[2];
	u8 buf[2];
	int ret;

	buf[0] = (reg >> 8) & 0xFF;
	buf[1] = reg & 0xFF;

	msg[0].addr = client->addr;
	msg[0].flags = client->flags;
	msg[0].buf = buf;
	msg[0].len = sizeof(buf);

	msg[1].addr = client->addr;
	msg[1].flags = client->flags | I2C_M_RD;
	msg[1].buf = buf;
	msg[1].len = 1;

	ret = i2c_transfer(client->adapter, msg, 2);
	if (ret >= 0) {
		*val = buf[0];
		return 0;
	}

	dev_err(&client->dev,
		"og02c10 read reg(0x%x) failed, ret=%d\n", reg, ret);

	return ret;
}

/*
 * Module mount is optically mirrored vs FAE default (3821 mirror off).
 * Invert V4L2 HFLIP polarity so UI/CISFlip matches visual result:
 *   hflip=0 -> no mirror (upright view) -> HW mirror ON
 *   hflip=1 -> mirror              -> HW mirror OFF
 * Bayer remap / keep_view follow actual HW mirror/flip bits.
 */
static bool og02c10_hw_mirror_en(struct og02c10 *og02c10)
{
	if (!og02c10->h_flip)
		return false;
	return !og02c10->h_flip->val;
}

static bool og02c10_hw_flip_en(struct og02c10 *og02c10)
{
	return og02c10->v_flip ? !!og02c10->v_flip->val : false;
}

static u32 og02c10_get_bus_fmt(struct og02c10 *og02c10)
{
	u32 code = og02c10->cur_mode->bus_fmt;
	bool hw_mirror = og02c10_hw_mirror_en(og02c10);
	bool hw_flip = og02c10_hw_flip_en(og02c10);
	unsigned int idx = (hw_flip ? 2 : 0) | (hw_mirror ? 1 : 0);
	static const u32 map10[] = {
		MEDIA_BUS_FMT_SBGGR10_1X10,
		MEDIA_BUS_FMT_SGBRG10_1X10,
		MEDIA_BUS_FMT_SGRBG10_1X10,
		MEDIA_BUS_FMT_SRGGB10_1X10,
	};
	static const u32 map12[] = {
		MEDIA_BUS_FMT_SBGGR12_1X12,
		MEDIA_BUS_FMT_SGBRG12_1X12,
		MEDIA_BUS_FMT_SGRBG12_1X12,
		MEDIA_BUS_FMT_SRGGB12_1X12,
	};

	if (code == MEDIA_BUS_FMT_SBGGR10_1X10 ||
	    code == MEDIA_BUS_FMT_SGBRG10_1X10 ||
	    code == MEDIA_BUS_FMT_SGRBG10_1X10 ||
	    code == MEDIA_BUS_FMT_SRGGB10_1X10)
		return map10[idx];
	if (code == MEDIA_BUS_FMT_SBGGR12_1X12 ||
	    code == MEDIA_BUS_FMT_SGBRG12_1X12 ||
	    code == MEDIA_BUS_FMT_SGRBG12_1X12 ||
	    code == MEDIA_BUS_FMT_SRGGB12_1X12)
		return map12[idx];

	return code;
}

static int og02c10_update_keep_view(struct og02c10 *og02c10)
{
	u8 val = 0;
	int ret;
	bool hw_mirror = og02c10_hw_mirror_en(og02c10);
	bool hw_flip = og02c10_hw_flip_en(og02c10);

	ret = og02c10_read_reg(og02c10->client, OG02C10_REG_WINDOW_CTRL_8, &val);
	if (ret)
		return ret;

	/* HW mirror/flip on: clear keep_view so Bayer phase follows readout */
	if (hw_mirror)
		val &= ~OG02C10_MIRROR_KEEP_VIEW_EN;
	else
		val |= OG02C10_MIRROR_KEEP_VIEW_EN;

	if (hw_flip)
		val &= ~OG02C10_FLIP_KEEP_VIEW_EN;
	else
		val |= OG02C10_FLIP_KEEP_VIEW_EN;

	return og02c10_write_reg(og02c10->client, OG02C10_REG_WINDOW_CTRL_8, val);
}

static int og02c10_get_reso_dist(const struct og02c10_mode *mode,
				 struct v4l2_mbus_framefmt *framefmt)
{
	return abs(mode->width - framefmt->width) +
		abs(mode->height - framefmt->height);
}

static const struct og02c10_mode *
og02c10_find_best_fit(struct og02c10 *og02c10, struct v4l2_subdev_format *fmt)
{
	struct v4l2_mbus_framefmt *framefmt = &fmt->format;
	int dist;
	int cur_best_fit = 0;
	int cur_best_fit_dist = -1;
	unsigned int i;

	for (i = 0; i < og02c10->cfg_num; i++) {
		dist = og02c10_get_reso_dist(&supported_modes[i], framefmt);
		if ((cur_best_fit_dist == -1 || dist <= cur_best_fit_dist) &&
		    (supported_modes[i].bus_fmt == framefmt->code)) {
			cur_best_fit_dist = dist;
			cur_best_fit = i;
		}
	}

	return &supported_modes[cur_best_fit];
}


static void og02c10_update_controls(struct og02c10 *og02c10)
{
	const struct og02c10_mode *mode = og02c10->cur_mode;
	s64 v_blank = mode->vts_def - mode->height;
	u64 pixels_per_line;
	u32 h_blank;
	u64 dst_link_freq = 0;
	u64 dst_pixel_rate = og02c10_get_pixel_rate(mode);
	s64 exposure_max;

	/* HTS is in SCLK cycles; V4L2 HBLANK is in pixel-rate cycles. */
	pixels_per_line = og02c10_get_pixels_per_line(mode);
	if (pixels_per_line > mode->width) {
		h_blank = pixels_per_line - mode->width;
	} else {
		dev_warn(&og02c10->client->dev,
			 "pixels_per_line(%llu) <= width(%u), report hblank=0\n",
			 (unsigned long long)pixels_per_line, mode->width);
		h_blank = 0;
	}

	__v4l2_ctrl_modify_range(og02c10->hblank, h_blank,
					 h_blank, 1, h_blank);
	__v4l2_ctrl_modify_range(og02c10->vblank, v_blank,
					 OG02C10_VTS_MAX - mode->height,
					 1, v_blank);
	/* FAE: DCG max=VTS-8; Linear max=VTS/2-12 */
	if (mode->bus_fmt == MEDIA_BUS_FMT_SBGGR12_1X12)
		exposure_max = mode->vts_def - OG02C10_EXPOSURE_DCG_MARGIN;
	else
		exposure_max = mode->vts_def / 2 - OG02C10_EXPOSURE_LINEAR_MARGIN;
	__v4l2_ctrl_modify_range(og02c10->exposure, OG02C10_EXPOSURE_MIN,
				 exposure_max, OG02C10_EXPOSURE_STEP,
				 mode->exp_def);
	if (og02c10->anal_gain) {
		s64 gain_min = OG02C10_GAIN_MIN;
		s64 gain_max = OG02C10_GAIN_MAX;
		s64 gain_def = OG02C10_GAIN_DEFAULT;

		if (mode->bus_fmt == MEDIA_BUS_FMT_SBGGR12_1X12) {
			/* logical gain: 1x..~29x, driver *8 -> HCG */
			gain_min = OG02C10_DCG_GAIN_MIN;
			gain_max = OG02C10_DCG_GAIN_MAX;
			gain_def = OG02C10_DCG_GAIN_DEFAULT;
		}
		__v4l2_ctrl_modify_range(og02c10->anal_gain, gain_min,
					 gain_max, OG02C10_GAIN_STEP,
					 gain_def);
	}
	__v4l2_ctrl_s_ctrl_int64(og02c10->pixel_rate, dst_pixel_rate);
	__v4l2_ctrl_s_ctrl(og02c10->link_freq, dst_link_freq);
}

static int og02c10_set_fmt(struct v4l2_subdev *sd,
			   struct v4l2_subdev_state *sd_state,
			   struct v4l2_subdev_format *fmt)
{
	struct og02c10 *og02c10 = to_og02c10(sd);
	const struct og02c10_mode *mode;

	mutex_lock(&og02c10->mutex);
	mode = og02c10_find_best_fit(og02c10, fmt);
	fmt->format.code = mode->bus_fmt;
	fmt->format.width = mode->width;
	fmt->format.height = mode->height;
	fmt->format.field = V4L2_FIELD_NONE;
	if (fmt->which == V4L2_SUBDEV_FORMAT_TRY) {
#ifdef CONFIG_VIDEO_V4L2_SUBDEV_API
		*v4l2_subdev_get_try_format(sd, sd_state, fmt->pad) = fmt->format;
#else
		mutex_unlock(&og02c10->mutex);
		return -ENOTTY;
#endif
	} else {
		og02c10->cur_mode = mode;
		og02c10_update_controls(og02c10);
	}

	mutex_unlock(&og02c10->mutex);

	return 0;
}

static int og02c10_get_fmt(struct v4l2_subdev *sd,
			   struct v4l2_subdev_state *sd_state,
			   struct v4l2_subdev_format *fmt)
{
	struct og02c10 *og02c10 = to_og02c10(sd);
	const struct og02c10_mode *mode = og02c10->cur_mode;

	mutex_lock(&og02c10->mutex);
	if (fmt->which == V4L2_SUBDEV_FORMAT_TRY) {
		dev_dbg(&og02c10->client->dev, "get format try.\n");
#ifdef CONFIG_VIDEO_V4L2_SUBDEV_API
		fmt->format = *v4l2_subdev_get_try_format(sd, sd_state, fmt->pad);
#else
		mutex_unlock(&og02c10->mutex);
		return -ENOTTY;
#endif
	} else {
		fmt->format.width = mode->width;
		fmt->format.height = mode->height;
		fmt->format.code = og02c10_get_bus_fmt(og02c10);
		fmt->format.field = V4L2_FIELD_NONE;
		if (fmt->pad < PAD_MAX && mode->hdr_mode != NO_HDR)
			fmt->reserved[0] = mode->vc[fmt->pad];
		else
			fmt->reserved[0] = mode->vc[PAD0];
	}
	mutex_unlock(&og02c10->mutex);

	dev_dbg(&og02c10->client->dev,
		"get format, width: %d, height: %d, code: %d, field: %d.\n",
		fmt->format.width, fmt->format.height,
		fmt->format.code, fmt->format.field);

	return 0;
}

static int og02c10_enum_mbus_code(struct v4l2_subdev *sd,
				  struct v4l2_subdev_state *sd_state,
				  struct v4l2_subdev_mbus_code_enum *code)
{
	struct og02c10 *og02c10 = to_og02c10(sd);

	if (code->index >= og02c10->cfg_num)
		return -EINVAL;
	code->code = supported_modes[code->index].bus_fmt;

	return 0;
}

static int og02c10_enum_frame_sizes(struct v4l2_subdev *sd,
				    struct v4l2_subdev_state *sd_state,
				    struct v4l2_subdev_frame_size_enum *fse)
{
	struct og02c10 *og02c10 = to_og02c10(sd);

	if (fse->index >= og02c10->cfg_num)
		return -EINVAL;

	if (fse->code != supported_modes[fse->index].bus_fmt)
		return -EINVAL;

	fse->min_width	= supported_modes[fse->index].width;
	fse->max_width	= supported_modes[fse->index].width;
	fse->max_height = supported_modes[fse->index].height;
	fse->min_height = supported_modes[fse->index].height;

	return 0;
}

static int og02c10_g_frame_interval(struct v4l2_subdev *sd,
				    struct v4l2_subdev_frame_interval *fi)
{
	struct og02c10 *og02c10 = to_og02c10(sd);
	const struct og02c10_mode *mode = og02c10->cur_mode;

	fi->interval = mode->max_fps;

	return 0;
}

static int og02c10_g_mbus_config(struct v4l2_subdev *sd, unsigned int pad,
		struct v4l2_mbus_config *config)
{
	config->type = V4L2_MBUS_CSI2_DPHY;
	config->bus.mipi_csi2.num_data_lanes = OG02C10_LANES;

	return 0;
}

static void og02c10_get_module_inf(struct og02c10 *og02c10,
		  struct rkmodule_inf *inf)
{
	memset(inf, 0, sizeof(*inf));
	strscpy(inf->base.sensor, OG02C10_NAME, sizeof(inf->base.sensor));
	strscpy(inf->base.module, og02c10->module_name,
	sizeof(inf->base.module));
	strscpy(inf->base.lens, og02c10->len_name, sizeof(inf->base.lens));
}


static int og02c10_set_hdr_cfg(struct og02c10 *og02c10,
				       struct rkmodule_hdr_cfg *hdr_cfg)
{
	u32 i, h, w;

	w = og02c10->cur_mode->width;
	h = og02c10->cur_mode->height;
	if (og02c10->cur_mode->hdr_mode == hdr_cfg->hdr_mode)
		return 0;

	for (i = 0; i < og02c10->cfg_num; i++) {
		if (w == supported_modes[i].width &&
		    h == supported_modes[i].height &&
		    supported_modes[i].hdr_mode == hdr_cfg->hdr_mode) {
			og02c10->cur_mode = &supported_modes[i];
			og02c10_update_controls(og02c10);
			return 0;
		}
	}

	dev_err(&og02c10->client->dev,
		"not find hdr mode:%d %dx%d config\n",
		hdr_cfg->hdr_mode, w, h);
	return -EINVAL;
}

static long og02c10_ioctl(struct v4l2_subdev *sd, unsigned int cmd, void *arg)
{
	struct og02c10 *og02c10 = to_og02c10(sd);
	struct rkmodule_hdr_cfg *hdr_cfg;
	long ret = 0;
	u32 stream = 0;

	switch (cmd) {
	case RKMODULE_SET_HDR_CFG:
		hdr_cfg = (struct rkmodule_hdr_cfg *)arg;
		ret = og02c10_set_hdr_cfg(og02c10, hdr_cfg);
		break;
	case RKMODULE_GET_MODULE_INFO:
		og02c10_get_module_inf(og02c10, (struct rkmodule_inf *)arg);
		break;
	case RKMODULE_GET_HDR_CFG:
		hdr_cfg = (struct rkmodule_hdr_cfg *)arg;
		hdr_cfg->hdr_mode = og02c10->cur_mode->hdr_mode;
		hdr_cfg->esp.mode = HDR_NORMAL_VC;
		//if (hdr_cfg->hdr_mode == HDR_CIS_MERGE && og02c10->cur_mode->hdr_compr)
		//	hdr_cfg->compr = *og02c10->cur_mode->hdr_compr;
		break;
	case RKMODULE_SET_QUICK_STREAM:
		stream = *((u32 *)arg);
		if (stream)
			ret = og02c10_write_reg(og02c10->client, OG02C10_REG_CTRL_MODE,
						OG02C10_MODE_STREAMING);
		else
			ret = og02c10_write_reg(og02c10->client, OG02C10_REG_CTRL_MODE,
						OG02C10_MODE_SW_STANDBY);
		break;
	default:
		ret = -ENOIOCTLCMD;
		break;
	}

	return ret;
}

